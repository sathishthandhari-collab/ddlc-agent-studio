"""Python AST syntax validator and immutable Skeleton header enforcement."""

from __future__ import annotations

import ast

SKELETON_BANNER_LINE = "# DO NOT EDIT. Autogenerated deterministically by DDLC Compiler from impl_docs."


class CompilerSyntaxError(SyntaxError):
    """Raised when compiled Python code fails ast.parse()."""


def make_skeleton_header(rel_posix_path: str) -> str:
    """Return the canonical immutable Skeleton file header (builder.md §2.1)."""
    return (
        "# ==============================================================================\n"
        f"{SKELETON_BANNER_LINE}\n"
        f"# File: {rel_posix_path}\n"
        "# ==============================================================================\n"
    )


def validate_python_ast(source: str, filename: str = "<generated>") -> ast.Module:
    """Parse Python source with ast.parse() and raise CompilerSyntaxError on failure."""
    try:
        return ast.parse(source, filename=filename)
    except SyntaxError as exc:
        raise CompilerSyntaxError(
            f"AST syntax error in {filename} at line {exc.lineno}: {exc.msg}"
        ) from exc


def has_skeleton_header(source: str) -> bool:
    """Return True if source contains the immutable compiler banner."""
    return SKELETON_BANNER_LINE in source[:512]
